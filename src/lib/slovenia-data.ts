/**
 * NORMALIZACIJA INTERESOV (kanon izvirnika za vnos uporabnika):
 * ", LOVe, ; kajakovANJE , kajakovanje," → ["love", "kajakovanje"]
 * - ločila: vejice, podpičja, nove vrstice
 * - male črke, trimmed, prazni in duplikati odstranjeni
 * - deterministično (isti vhod → isti izhod)
 */
export function normalizeInterests(input: string): string[] {
  return [
    ...new Set(
      input
        .split(/[,;\n]+/)
        .map((s) => s.trim().toLowerCase())
        .filter((s) => s.length > 0)
    ),
  ];
}

